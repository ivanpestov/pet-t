//! Исход прогона Таймера.

/// Исход прогона Таймера. Хранит только сведения, влияющие на код выхода;
/// перевод исхода в код выполняет бинарный крейт. Ошибки отображения при
/// прерывании и сне на код не влияют и в исходе не сохраняются.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Outcome {
    /// Естественное завершение: успешность отображения итогового состояния
    /// и закрытия Учитываемого периода.
    Completed { displayed: bool, closed: bool },
    /// Прерывание по Ctrl+C: успешность закрытия Учитываемого периода.
    Interrupted { closed: bool },
    /// Завершение по сну: успешность закрытия Учитываемого периода.
    Suspended { closed: bool },
    /// Отказ: подготовка, чтение времени, мониторинг, канал событий или
    /// обязательное отображение состояния.
    Failed,
}
